#!/usr/bin/env python3
"""Write docs/SKIPPED.md — every source not built, and why.

CLAUDE.md, Working rules: "Log every skipped or failed source with the reason."
That was satisfied only in pieces — the catalog's `buildable` column, its
`has_questionnaire` column, the transfer screen's JSON — so no one place said
how many sources we had declined and on what grounds. Which means nobody could
notice that a reason had changed, or that a source had become buildable.

GENERATED, not hand-maintained, for the same reason the ledger is hand-written:
a list of 180-odd rows kept by hand goes stale in a week and then misleads. Re-run
it whenever the catalog or the screens change.

    uv run python scripts/skipped_report.py
"""

from __future__ import annotations

import csv
import json
from collections import defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
CATALOG = REPO / "data" / "catalog" / "tess_uk_foundation_sources.csv"
SCREEN = REPO / "data" / "catalog" / "uk_transfer_screen.json"
RECIPES = REPO / "recipes"
OUT = REPO / "docs" / "SKIPPED.md"

# Why a source is not built, most decisive reason first — a source with no
# access is not also "no questionnaire", it is simply unavailable.
REASONS = {
    "no_access": (
        "**No access.** The deposit is restricted or its files could not be "
        "retrieved. Nothing to build from."
    ),
    "no_questionnaire": (
        "**No fielded questionnaire in the deposit.** `docs/CONVENTIONS.md` makes the "
        "questionnaire the only authority on stimulus wording, and a proposal is not a "
        "substitute — the reference dataset built at least three studies from proposals "
        "using words no respondent saw. Buildable only if an instrument turns up."
    ),
    "outcome_needs_local_knowledge": (
        "**The outcome needs US knowledge.** Answering requires knowing US law, "
        "politics or institutions, so a UK respondent has no view to predict. Not "
        "rescuable by re-setting the scenario. Screened by "
        "`scripts/uk_content_screen.py`; a verdict here is the SCREEN's, and the screen "
        "agrees with hand reading on 12 of 16, so treat it as a queue order, not a "
        "ruling."
    ),
    "not_yet_reached": (
        "**Not yet reached.** Buildable, in scope, simply not built — the plan targets "
        "20% of the catalogue chosen for value, not 100%."
    ),
}


def main() -> int:
    with open(CATALOG) as fh:
        rows = list(csv.DictReader(fh))
    screen = json.loads(SCREEN.read_text()) if SCREEN.exists() else {}
    built = {p.stem.split("_")[0] for p in RECIPES.glob("*.yaml")}

    groups: dict[str, list[tuple[str, str, str]]] = defaultdict(list)
    for r in rows:
        code = r["osf_code"]
        if code in built:
            continue
        if r.get("buildable") == "no-access":
            why = "no_access"
        elif r.get("has_questionnaire") == "no":
            why = "no_questionnaire"
        elif screen.get(code, {}).get("verdict") == "us-specific":
            why = "outcome_needs_local_knowledge"
        else:
            why = "not_yet_reached"
        groups[why].append((code, r.get("year", ""), r.get("title", "")))

    total = sum(len(v) for v in groups.values())
    lines = [
        "# Sources not built, and why",
        "",
        "<!-- GENERATED by scripts/skipped_report.py — do not edit by hand. -->",
        "",
        f"{len(built)} of {len(rows)} catalogued sources are built. "
        f"The remaining {total} are listed below, grouped by the reason.",
        "",
        "A reason here is a *decision*, and decisions can be revisited: a source with "
        "no questionnaire becomes buildable the moment an instrument turns up, and a "
        "screen verdict is a queue order rather than a ruling.",
        "",
    ]
    for why in REASONS:
        items = sorted(groups.get(why, []))
        if not items:
            continue
        lines += [f"## {why.replace('_', ' ').title()} — {len(items)}", "", REASONS[why], ""]
        if why == "not_yet_reached":
            lines += [
                "Listed as a count rather than individually; "
                "`data/catalog/uk_shortlist.json` holds the ones queued next.",
                "",
            ]
            continue
        lines += ["| code | year | title |", "|---|---|---|"]
        lines += [f"| `{c}` | {y} | {t[:76]} |" for c, y, t in items]
        lines.append("")

    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(REPO)}")
    for why in REASONS:
        if groups.get(why):
            print(f"  {why:32} {len(groups[why])}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
