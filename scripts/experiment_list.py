#!/usr/bin/env python3
"""Render the one list of built and candidate experiments, as Markdown and as a page.

rich asked (2026-10-10) for a single, consistent list: every built experiment and
every candidate, one status scale, the same columns in every section, and local
copies. Both outputs come from one data file so they cannot drift apart:

    data/catalog/experiment_list.json   the rows (study metadata only)
    docs/EXPERIMENT_LIST.md             generated Markdown
    docs/trackers/text_experiments.html generated full-width page

Statuses, defined once and used everywhere:

    Built           already in the corpus
    Buildable       not built; condition text, outcome and allocation appear to exist
    Needs checking  not built; something must be read or found first (the row says what)
    Unlikely        not built; probably breaks one of our rules (the row says which)

    uv run python scripts/experiment_list.py
"""

from __future__ import annotations

import json
import re
import subprocess
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "catalog" / "experiment_list.json"
MD = ROOT / "docs" / "EXPERIMENT_LIST.md"
HTML = ROOT / "docs" / "trackers" / "text_experiments.html"
TEMPLATE = ROOT / "scripts" / "experiment_list_template.html"

SOURCES = ["Innovation Panel", "DEL", "TESS", "Harvard Dataverse"]
STATUSES = ["Built", "Buildable", "Needs checking", "Unlikely"]
DEFINITIONS = {
    "Built": "Already in the corpus, checked and on disk.",
    "Buildable": (
        "Not built. The condition text, the outcome and the record of who saw which "
        "condition all appear to exist. Still gets the full check when built."
    ),
    "Needs checking": "Not built. Something must be read or found first; the row says what.",
    "Unlikely": (
        "Not built. Probably breaks one of our rules (an image condition, no shared "
        "outcome, needs US knowledge, no data); the row says which."
    ),
}


def _cell(text: str) -> str:
    return str(text).replace("|", "/").replace("\n", " ").strip()


def _sort_key(r: dict) -> tuple:
    # Study before novelty, so one study's experiments sit together (rich, 12 Oct 2026).
    nov = r.get("novelty")
    return (
        STATUSES.index(r["status"]),
        r.get("study") or "",
        -(nov if nov is not None else -1.0),
        _experiment_id(r),
    )


def _experiment_id(r: dict) -> str:
    """The recipe name once built (the name the code, parquets and split use);
    the source's own id before that, as there is no recipe yet."""
    return r.get("recipe") or r["id"]


_DEL_WAVE = re.compile(r"^(W\d+|[A-Z][a-z]{2}\d{4})_")


def candidate_study(r: dict) -> str | None:
    """The study an unbuilt candidate would fall in, named as make_splits.study_of
    names it, read from the source's own id. None when the id does not say."""
    if r["source"] == "Innovation Panel" and re.fullmatch(r"\d+\.\d+", r["id"]):
        return f"ukds_6849:{r['id']}"
    if r["source"] == "DEL" and (m := _DEL_WAVE.match(r["id"])):
        wave = m.group(1).lower()
        return f"del:panel_{wave}" if wave.startswith("w") else f"del:sandbox_{wave}"
    if r["source"] in ("TESS", "Harvard Dataverse") and re.fullmatch(r"[0-9A-Za-z]+", r["id"]):
        return r["id"]
    return None


def render_md(data: dict) -> str:
    rows = data["rows"]
    out = [
        "# SocSci-UK Experiment List",
        "",
        "<!-- GENERATED by scripts/experiment_list.py from data/catalog/experiment_list.json"
        " — do not edit by hand. -->",
        "",
        "Every experiment we have built and every candidate we could add, from four sources,"
        " with one status scale and the same columns in every section.",
        "",
        "## Summary",
        "",
        "| Source | People and licence | "
        + " | ".join(STATUSES)
        + " | Not built, total | Rows built |",
        "| :--- | :--- | " + " | ".join([":---"] * len(STATUSES)) + " | :--- | :--- |",
    ]

    def n(src: str | None = None, st: str | None = None) -> int:
        return sum(
            1
            for r in rows
            if (src is None or r["source"] == src) and (st is None or r["status"] == st)
        )

    for s in SOURCES:
        cells = [str(n(s, st)) for st in STATUSES]
        out.append(
            f"| {s} | {data['meta'][s]} | "
            + " | ".join(cells)
            + f" | {n(s) - n(s, 'Built')} | {rows_built(rows, s):,} |"
        )
    totals = [f"**{n(None, st)}**" for st in STATUSES]
    out.append(
        "| **Total** | | "
        + " | ".join(totals)
        + f" | **{len(rows) - n(None, 'Built')}** | **{rows_built(rows, None):,}** |"
    )
    nxt = sorted((r for r in rows if r.get("next")), key=lambda r: r["next"])
    if nxt:
        ranks = {r["next"] for r in nxt}
        done = sum(all(x["status"] == "Built" for x in nxt if x["next"] == k) for k in ranks)
        out += [
            "",
            f"## Next {len(ranks)}, in build order ({done} built, {len(ranks) - done} to go)",
            "",
        ]
        out += [f"- {m}" for m in data.get("next_batch", {}).get("method", [])]
        out += [
            "",
            "| Next | Source | ID | Experiment | Category | Novelty |",
            "| :--- | :--- | :--- | :--- | :--- | :--- |",
        ]
        for r in nxt:
            nov = "" if r.get("novelty") is None else f"{r['novelty']:.2f}"
            out.append(
                f"| {r['next']} | {r['source']} | {_cell(r['id'])} | **{_cell(r['title'])}**"
                f"<br>{_cell(r.get('description', ''))} | {_cell(r['category'])} | {nov} |"
            )
    out += ["", "## Statuses", ""]
    out += [f"- **{k}:** {v}" for k, v in DEFINITIONS.items()]
    out += [
        "",
        "**Novelty** (0 to 0.33) is how far a candidate's title sits from the nearest built"
        " title. Higher means less like anything we already hold.",
    ]
    for s in SOURCES:
        src_rows = sorted((r for r in rows if r["source"] == s), key=_sort_key)
        counts = ", ".join(f"{n(s, st)} {st}" for st in STATUSES)
        out += [
            "",
            f"## {s}",
            "",
            f"{data['meta'][s]}. {counts}.",
            "",
            "| Study ID | Split | Experiment ID | Experiment | Category | Status | Novelty | Next"
            " | Rows |",
            "| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |",
        ]
        for r in src_rows:
            exp = f"**{_cell(r['title'])}**"
            if r.get("description"):
                exp += f"<br>{_cell(r['description'])}"
            if r.get("details"):
                exp += f"<br>*{_cell(r['details'])}*"
            status = r["status"] + (f": {_cell(r['reason'])}" if r.get("reason") else "")
            nov = "" if r.get("novelty") is None else f"{r['novelty']:.2f}"
            out.append(
                f"| {r.get('study') or ''} | {r.get('split', '')} | {_cell(_experiment_id(r))} "
                f"| {exp} | {_cell(r['category'])} | {status} | {nov} | {r.get('next', '')} "
                f"| {_rows(r)} |"
            )
    return "\n".join(out) + "\n"


def _rows(r: dict) -> str:
    return f"{r['rows']:,}" if r.get("rows") is not None else ""


def rows_built(rows: list[dict], src: str | None) -> int:
    return sum(r.get("rows") or 0 for r in rows if src is None or r["source"] == src)


def text_recipes() -> set[str]:
    """Committed recipes for TEXT experiments: every tracked recipe, less image ones.

    Image experiments live in recipes/images/ and are listed on their own page
    (scripts/image_experiments.py), so they are neither rows here nor counted here.
    """
    out = subprocess.run(
        ["git", "ls-files", "recipes/*.yaml"], cwd=ROOT, capture_output=True, text=True
    )
    # git's pathspec "*" crosses "/", so recipes/images/ would otherwise be included.
    return {p for p in out.stdout.split() if not p.startswith("recipes/images/")}


def attach_row_counts(data: dict) -> None:
    """Give every Built row its experiment's row count, read from the built parquet.

    Each Built row names its recipe; the recipe names its study and experiment, and
    the parquet holding that (study, experiment) supplies the count. A Built row with
    no recipe, or a committed recipe no Built row names, stops the page: the count on
    it would otherwise be wrong without looking wrong.
    """
    import pandas as pd

    committed = text_recipes()
    sizes: dict[tuple[str, str | None], int] = {}
    for pq in (ROOT / "data" / "processed").glob("*.parquet"):
        df = pd.read_parquet(pq, columns=["study_id", "experiment"])
        for (sid, exp), n in df.groupby(["study_id", "experiment"], dropna=False).size().items():
            sizes[(str(sid), None if pd.isna(exp) else str(exp))] = int(n)
    splits = ROOT / "data" / "catalog" / "splits"
    study_of = json.loads((splits / "study_of_recipe.json").read_text())
    unseen = set(json.loads((splits / "participant_mapping.json").read_text())["unseen"])
    excluded = set(json.loads((splits / "excluded.json").read_text()))
    named = set()
    for r in data["rows"]:
        if r["status"] != "Built":
            continue
        path = f"recipes/{r.get('recipe')}.yaml"
        if path not in committed:
            raise SystemExit(f"Built row {r['id']} names no committed recipe ({path})")
        named.add(path)
        rec = yaml.safe_load((ROOT / path).read_text())
        key = (str(rec["study_id"]), rec.get("experiment"))
        if key not in sizes:
            raise SystemExit(f"{path}: no built parquet holds {key}")
        r["rows"] = sizes[key]
        # The study id the seen/unseen split uses, and its side, so the page and the
        # split speak the same identifiers (rich, 12 Oct 2026).
        r["study"] = study_of[r["recipe"]]
        r["split"] = (
            "excluded" if r["study"] in excluded else "unseen" if r["study"] in unseen else "seen"
        )
        # Where a built row still carries its source id, reading the study from it must
        # agree with the split's own mapping, or candidates' study ids can't be trusted.
        if (guess := candidate_study(r)) is not None and guess != r["study"]:
            raise SystemExit(
                f"{r['id']}: study read from its id is {guess}, split says {r['study']}"
            )
    if unnamed := sorted(committed - named):
        raise SystemExit(f"committed recipes with no Built row: {unnamed}")
    for r in data["rows"]:
        if r["status"] != "Built":
            r["study"] = candidate_study(r)  # no split: unbuilt work is in no split


def corpus_experiments() -> int:
    """Experiments in the committed corpus: one per tracked recipe.

    A built study can be several experiments (one per answer type or sub-design),
    so this differs from the Built count above, which counts studies. Untracked
    recipes are work in progress and are not counted.
    """
    return len(text_recipes())


def render_html(data: dict) -> str:
    payload = json.dumps(data, ensure_ascii=False).replace("</", "<\\/")
    return TEMPLATE.read_text().replace("__DATA__", payload)


def main() -> None:
    data = json.loads(DATA.read_text())
    bad = {r["status"] for r in data["rows"]} - set(STATUSES)
    if bad:
        raise SystemExit(f"unknown status in {DATA.name}: {sorted(bad)}")
    # One row per experiment, as the list has always been: a study built in several
    # parts gets a row per part (35M5CV, py9q3). On 10 Oct new multi-part builds were
    # entered as one row each and the page drifted to 84 Built against 95 experiments.
    built = sum(r["status"] == "Built" for r in data["rows"])
    if built != (n_exp := corpus_experiments()):
        raise SystemExit(
            f"{built} rows are Built but {n_exp} recipes are committed — give each built "
            "experiment its own row"
        )
    attach_row_counts(data)
    MD.write_text(render_md(data))
    HTML.write_text(render_html(data))
    print(
        f"wrote {MD.relative_to(ROOT)} and {HTML.relative_to(ROOT)}: {len(data['rows'])} experiments"
    )


if __name__ == "__main__":
    main()
