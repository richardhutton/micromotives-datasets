def answer_columns(names: list[str]) -> dict[str, int]:
    """QID -> its Data.xlsx column, checked against the .qsf export tags."""
    out = {}
    i = FIRST_DATA_COL
    for block in CARD_BLOCKS:
        for q in card_block(block):
            if names[i] != q["DataExportTag"]:
                raise SystemExit(f"column {i} is {names[i]!r}, .qsf says {q['DataExportTag']!r}")
            out[q["QuestionID"]] = i
            i += 1
    return out


def kept(names: list[str], rows: pd.DataFrame) -> pd.Series:
    """The authors' inclusion: Progress 99/100 and the attention check passed."""
    col = {n: i for i, n in enumerate(names) if names.count(n) == 1}
    done = rows[col["Progress"]].astype(str).isin(["100", "99"])
    attentive = rows[col["Attention_check_recoded"]].astype(str) != "0"
    out: pd.Series = done & attentive
    return out


def prep() -> pd.DataFrame:
    """The coded long spreadsheet: one row per UK person per card."""
    names, rows = raw_export()
    col = {n: i for i, n in enumerate(names) if names.count(n) == 1}
    keep = kept(names, rows)
    if int(keep.sum()) != EXPECTED_KEPT_ALL:
        raise SystemExit(f"{int(keep.sum())} kept in both countries, expected {EXPECTED_KEPT_ALL}")
    uk = prolific("UK").set_index("Participant id")
    us_ids = set(prolific("US")["Participant id"])
    if set(uk.index) & us_ids:
        raise SystemExit("a Prolific ID is in both the UK and the US exports")
    pids = rows[col["PROLIFIC_PID"]]
    take = keep & pids.isin(set(uk.index))
    if int(take.sum()) != EXPECTED_UK or pids[take].duplicated().any():
        raise SystemExit(f"{int(take.sum())} UK people kept, expected {EXPECTED_UK} unique")
    acol = answer_columns(names)
    block_slots = {b: slots(b) for b in CARD_BLOCKS}
    arm_of = {fl: a for a, (_, fl, _, _, _) in enumerate(INSTRUCTIONS, start=1)}
    _, trust_labels = trust_pre()
    out = []
    for i in rows.index[take]:
        r = rows.loc[i]
        a = arm_of[r[col["FL_61_DO"]]]
        block = r[col["FL_72_DO"]] if a == 1 else r[col["FL_74_DO"]]
        expected_blocks = CARD_BLOCKS[:2] if a == 1 else CARD_BLOCKS[2:]
        if block not in expected_blocks:
            raise SystemExit(f"row {i + 1}: arm {a} routed to {block!r}")
        info = uk.loc[r[col["PROLIFIC_PID"]]]
        if (info.astype(str) == REVOKED).any():
            raise SystemExit(f"row {i + 1}: Prolific consent revoked")
        order = str(r[col[f"{block}_DO"]]).split("|")
        sl = block_slots[block]
        by_tag = {s["sha_tag"]: s for s in sl}
        if len(order) != 20 or sorted(order[0::2]) != sorted(by_tag):
            raise SystemExit(f"row {i + 1}: display order does not list the block's ten cards")
        for page, (sha_tag, acc_tag) in enumerate(zip(order[0::2], order[1::2], strict=True)):
            fixed = sl[page]
            if acc_tag.strip().lower() != fixed["acc_tag"].strip().lower():
                raise SystemExit(f"row {i + 1} page {page + 1}: {acc_tag!r} not the fixed slot")
            shown = by_tag[sha_tag]
            story, version = shown["picture"]
            share = r[acol[shown["sha_qid"]]]
            accuracy = r[acol[fixed["acc_qid"]]]
            values = {}
            for name, v in (("SHARE", share), ("ACCURACY", accuracy)):
                if pd.isna(v) or int(v) not in range(1, 7):
                    raise SystemExit(f"row {i + 1} {name}: {v!r}")
                values[name] = int(v)
            rec: dict[str, Any] = {
                ID_VAR: i + 1,
                CARD_VAR: a * 100 + picture_index(story, version),
                **values,
            }
            for var in PERSONA_PROLIFIC.values():
                v = _label(info[var])
                rec[var] = int(v) if var == "Age" else v
            for var in TRUST_VARS:
                rec[var] = trust_labels[int(r[col[var]]) - 1]
            out.append(rec)
    return pd.DataFrame(out)


