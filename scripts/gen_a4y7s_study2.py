def _grey64(path: Path) -> np.ndarray:
    """The picture reduced to 64x64 grey by macOS sips (as gen_zenodo10628634 crops)."""
    with tempfile.TemporaryDirectory() as tmp:
        bmp = Path(tmp) / "p.bmp"
        subprocess.run(
            ["sips", "-z", "64", "64", "-s", "format", "bmp", str(path), "--out", str(bmp)],
            check=True,
            capture_output=True,
        )
        b = bmp.read_bytes()
    offset = int.from_bytes(b[10:14], "little")
    width = int.from_bytes(b[18:22], "little", signed=True)
    height = int.from_bytes(b[22:26], "little", signed=True)
    bpp = int.from_bytes(b[28:30], "little")
    if (width, abs(height), bpp) != (64, 64, 32):
        raise SystemExit(f"{path.name}: unexpected bitmap {width}x{height}x{bpp}")
    px = np.frombuffer(b[offset : offset + 64 * 64 * 4], dtype=np.uint8).reshape(64, 64, 4)
    grey: np.ndarray = px[:, :, :3].astype(float).mean(axis=2)
    return grey


def verify_graphics() -> dict[str, float]:
    """Each live Qualtrics graphic is the picture GRAPHIC_PICTURE says, and no other.
    Returns graphic -> its distance to that picture."""
    cards = {p: _grey64(HEADLINES / PICTURE_FILES[p]) for p in PICTURES}
    used = {s["graphic"] for b in CARD_BLOCKS for s in slots(b)}
    if used != set(GRAPHIC_PICTURE):
        raise SystemExit(f"live graphics differ from the mapping: {used ^ set(GRAPHIC_PICTURE)}")
    out = {}
    for graphic, picture in GRAPHIC_PICTURE.items():
        g = _grey64(GRAPHICS / graphic)
        dist = {p: float(np.abs(g - a).mean()) for p, a in cards.items()}
        nearest = min(dist, key=dist.__getitem__)
        runner_up = min(v for p, v in dist.items() if p != picture)
        if nearest != picture or dist[picture] > 1.0 or runner_up < 5.0:
            raise SystemExit(
                f"{graphic}: nearest {nearest} ({dist[nearest]:.2f}), mapped {picture}"
            )
        out[graphic] = dist[picture]
    return out


def catalogue_entries() -> dict[str, dict[str, str]]:
    """This study's entries in data/catalog/images.json."""
    from micromotives_datasets.images import sha256_of

    shown = {s["picture"] for b in CARD_BLOCKS for s in slots(b)}
    if shown != set(PICTURES):
        raise SystemExit(f"pictures shown differ from the catalogue: {shown ^ set(PICTURES)}")
    out: dict[str, dict[str, str]] = {}
    for story, version in PICTURES:
        f = image_file(story, version)
        sha = sha256_of(REPO / "data" / f)
        copy = DUPLICATE_COPIES.get((story, version))
        if copy and sha256_of(HEADLINES / copy) != sha:
            raise SystemExit(f"{copy} is not byte-identical to {f}")
        graphics = sorted(g for g, p in GRAPHIC_PICTURE.items() if p == (story, version))
        source = (
            f"https://osf.io/a4y7s/ (osfstorage, Study 2/Materials/Headlines/"
            f"{PICTURE_FILES[(story, version)]})"
        )
        if copy:
            source += f"; byte-identical copy at Headlines/{copy}"
        source += (
            f"; the same picture as Qualtrics graphic {' and '.join(graphics)}, which the "
            "survey's sharing question displays (Study 2/Materials/Qualtrics.qsf)"
        )
        out[image_id(story, version)] = {
            "file": f,
            "sha256": sha,
            "source": source,
            "licence": LICENCE + " The photograph is third-party material whose own terms the "
            "deposit does not state.",
            "text_in_image": text_in_image(story, version),
            "description": description(story, version),
        }
    return out


def write_catalogue() -> None:
    """Add or refresh only this study's entries; re-read first, others are editing too."""
    path = REPO / "data" / "catalog" / "images.json"
    current = json.loads(path.read_text())
    current.update(catalogue_entries())
    path.write_text(json.dumps(current, indent=2, ensure_ascii=False))


