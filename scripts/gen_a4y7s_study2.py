def _text(raw: str) -> str:
    """HTML to plain text. Typography only; words untouched."""
    raw = re.sub(r"<br\s*/?>|</p>|</div>", " ", raw)
    raw = re.sub(r"<[^>]+>", "", raw)
    raw = html.unescape(raw).replace("\xa0", " ")
    raw = raw.replace("’", "'").replace("‘", "'").replace("“", '"').replace("”", '"')
    return re.sub(r"\s+", " ", raw).strip()


def qsf() -> dict[str, Any]:
    out: dict[str, Any] = json.loads(QSF.read_text(encoding="utf-8-sig"))
    return out


def questions(d: dict[str, Any] | None = None) -> dict[str, dict[str, Any]]:
    d = qsf() if d is None else d
    return {
        e["Payload"]["QuestionID"]: e["Payload"]
        for e in d["SurveyElements"]
        if e["Element"] == "SQ"
    }


def block_payloads(d: dict[str, Any] | None = None) -> dict[str, dict[str, Any]]:
    """Live block description -> block payload. Trash skipped."""
    d = qsf() if d is None else d
    bl = next(e["Payload"] for e in d["SurveyElements"] if e["Element"] == "BL")
    bl = bl.values() if isinstance(bl, dict) else bl
    return {b["Description"].strip(): b for b in bl if b["Type"] != "Trash"}


def card_block(block: str, d: dict[str, Any] | None = None) -> list[dict[str, Any]]:
    """The block's 20 questions in block order: sharing, accuracy, sharing, ..."""
    d = qsf() if d is None else d
    qs = questions(d)
    b = block_payloads(d)[block]
    return [qs[x["QuestionID"]] for x in b["BlockElements"] if x["Type"] == "Question"]


def graphics_in(payload: dict[str, Any]) -> list[str]:
    return re.findall(r"IM=(IM_\w+)", payload.get("QuestionText", ""))


def slots(block: str, d: dict[str, Any] | None = None) -> list[dict[str, Any]]:
    """Per slot k (1..10): the sharing question, its graphic and picture, and the fixed
    accuracy question. Asserts the block's advanced randomisation shuffles only the
    sharing questions."""
    d = qsf() if d is None else d
    qs = card_block(block, d)
    if len(qs) != 20:
        raise SystemExit(f"{block}: {len(qs)} questions, expected 20")
    adv = block_payloads(d)[block]["Options"]["Randomization"]["Advanced"]
    sha_ids = [q["QuestionID"] for q in qs[0::2]]
    acc_ids = [q["QuestionID"] for q in qs[1::2]]
    if adv["FixedOrder"] != [x for a in acc_ids for x in ("{~Randomized~}", a)]:
        raise SystemExit(f"{block}: accuracy questions are not the fixed slots")
    if sorted(adv["RandomizeAll"]) != sorted(sha_ids) or str(adv["QuestionsPerPage"]) != "2":
        raise SystemExit(f"{block}: sharing questions are not the shuffled ones, two per page")
    out = []
    for k, (sha, acc) in enumerate(zip(qs[0::2], qs[1::2], strict=True), start=1):
        (graphic,) = graphics_in(sha)
        if graphics_in(acc):
            raise SystemExit(f"{block} slot {k}: accuracy question shows a picture")
        out.append(
            {
                "slot": k,
                "sha_qid": sha["QuestionID"],
                "sha_tag": sha["DataExportTag"],
                "acc_qid": acc["QuestionID"],
                "acc_tag": acc["DataExportTag"],
                "graphic": graphic,
                "picture": GRAPHIC_PICTURE[graphic],
            }
        )
    return out


def instruction_texts() -> dict[str, str]:
    """Arm key -> its instruction screen (first sentence dropped), plus reminder."""
    qs = questions()
    out = {}
    for key, _, qid, reminder, _ in INSTRUCTIONS:
        text = _text(qs[qid]["QuestionText"])
        if not text.startswith(MECHANICS + " "):
            raise SystemExit(f"{qid}: does not open with the mechanics sentence")
        text = text[len(MECHANICS) + 1 :]
        if reminder:
            text = f"{text} {_text(qs[reminder]['QuestionText'])}"
        out[key] = text
    if out["control"] != out["no_definition"]:
        raise SystemExit("Control and No Definition instruction screens differ")
    return out


def shared_context() -> str:
    """The instruction words every arm shares (a prefix)."""
    texts = list(instruction_texts().values())
    first = texts[0]
    if not all(t.startswith(first) for t in texts):
        raise SystemExit("the arms' instructions do not share the Control text as a prefix")
    return first


def definition_text(definition: str) -> str:
    """What a definition arm adds after shared_context ('' for none)."""
    texts = instruction_texts()
    key = next(k for k, _, _, _, level in INSTRUCTIONS if level == definition)
    return texts[key][len(shared_context()) :].strip()


def outcome_wording() -> tuple[tuple[str, list[str]], tuple[str, list[str]]]:
    """((sharing question, its six labels), (accuracy question, its six labels)), checked
    identical across all 40 copies of each."""
    seen: dict[str, set[tuple[str, tuple[str, ...]]]] = {"sha": set(), "acc": set()}
    for block in CARD_BLOCKS:
        for i, q in enumerate(card_block(block)):
            text = _text(re.sub(r"<img[^>]*>", "", q["QuestionText"]))
            labels = tuple(_text(q["Choices"][str(c)]["Display"]) for c in q["ChoiceOrder"])
            if [str(c) for c in q["ChoiceOrder"]] != [str(c) for c in range(1, 7)]:
                raise SystemExit(f"{q['QuestionID']}: choice ids are not 1..6")
            if q.get("RecodeValues"):
                raise SystemExit(f"{q['QuestionID']}: has a recode")
            seen["sha" if i % 2 == 0 else "acc"].add((text, labels))
    if len(seen["sha"]) != 1 or len(seen["acc"]) != 1:
        raise SystemExit(f"outcome wording varies: {seen}")
    ((sha_q, sha_l),) = seen["sha"]
    ((acc_q, acc_l),) = seen["acc"]
    return (sha_q, list(sha_l)), (acc_q, list(acc_l))


def trust_pre() -> tuple[list[str], list[str]]:
    """Q6: the three trust statements asked before the cards, and the seven answers."""
    (q,) = [p for p in questions().values() if p.get("DataExportTag") == "Q6"]
    if q["QuestionID"] not in {
        x["QuestionID"] for x in block_payloads()["Trust_pre"]["BlockElements"]
    }:
        raise SystemExit("Q6 is not the Trust_pre block's question")
    items = [_text(q["Choices"][str(c)]["Display"]) for c in q["ChoiceOrder"]]
    answers = [_text(q["Answers"][str(a)]["Display"]) for a in q["AnswerOrder"]]
    if [str(a) for a in q["AnswerOrder"]] != [str(a) for a in range(1, 8)]:
        raise SystemExit("Q6 answer ids are not 1..7")
    return items, answers


