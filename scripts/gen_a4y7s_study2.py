#!/usr/bin/env python3
"""Write recipes/images/a4y7s_study2.yaml: AI labels on headline cards, UK sample (IMG69).

Altay & Gilardi (2024), "People are skeptical of headlines labeled as AI-generated,
even if true or human-made, because they assume full AI automation", PNAS Nexus 3(10)
pgae403, doi 10.1093/pnasnexus/pgae403 (open access, PMC11443540). OSF project a4y7s
("GenAI labels"), folder "Study 2": the Qualtrics survey (Materials/Qualtrics.qsf and a
Word copy), the 40 card pictures (Materials/Headlines/{Control_A, Control_B, Labels_A,
Labels_B}), the raw Qualtrics export (Data and Stats/Raw/Data.xlsx), the six Prolific
demographic exports it is merged with ({Left, Center, Right}_{UK, US}.csv), the
authors' cleaning and analysis script (Script_clean.R) and their long file
(data_clean.xlsx). Study 1 (US only, a different design) is in the same deposit and is
not built here.

Study 2 ran on Prolific on 20-21 March 2024 in the US and the UK, each sample in
thirds by Prolific's political-affiliation screener. THIS RECIPE BUILDS THE UK SAMPLE
ONLY: 1,500 people. Each saw ten Facebook-style news cards (photograph, headline,
lede, no source), one per page in random order, and on each page answered a sharing
question and then an accuracy question (1-6).

Every judgement is here, in code, so the recipe can be re-derived and reviewed:

* DESIGN. Two randomisations. Between people, one of five instruction screens
  (`FL_61_DO`): Control (no labels), No Definition (AI-generated cards labelled), and
  Weak, Medium and Strong (labelled, plus a definition of "AI-generated"). Then one of
  two sets of ten stories (`FL_72_DO` for Control, `FL_74_DO` for the rest): each of
  ten stories exists in a human-written and an AI-written version, and set A shows one
  version of each story, set B the other. Within the person, the ten cards. So one row
  per person per card per question; the coded file is LONG (`pid`, `card`).
* WHICH CARD WAS SHOWN. Read from the instrument, never from the variable names. Each
  of the four card blocks (Control_A, Control_B, Label_A, Label_B) holds ten sharing
  questions, each displaying one Qualtrics graphic, and ten accuracy questions. The 39
  distinct graphics were fetched from the survey's own graphic URL
  (ipz.qualtrics.com/CP/Graphic.php?IM=<id>) and each is the same picture as one OSF
  card. The files are not byte-identical (Qualtrics re-encodes uploads), so --catalogue
  compares pixels: reduced to 64x64 grey by macOS sips, every graphic is within 0.41
  grey levels (of 255) of its card and at least 10.9 from any other. Two findings,
  both from that check:
  - Control_B's tenth sharing question shows the right card, the AI-written FALSE
    vaccine-injury card (set B's mirror of Control_A's human-written one), but is
    MIS-TAGGED `1_t_AI_nol_sha` (true, AI-written). Only the tag is wrong. The
    authors' script reads veracity from the tag, so their file codes it true; ours
    shows what was on screen.
  - Label_A's tenth sharing question is tagged `10_f_h_nol_sha` (false, human-written)
    but shows the same graphic as Control_B's tenth: the AI-written vaccine-injury card
    without a label. The human-written version, which the OSF folder Labels_A holds,
    was never shown to anyone in Label_A. So in the four labelled arms, set A, one
    AI-written card went unlabelled. The authors code it human-written.
  Neither changes a response; both change what a row says it showed, and the crosscheck
  asserts both differences rather than tolerating them.
* WHICH ACCURACY ANSWER BELONGS TO WHICH CARD. Each block's randomisation is
  "Advanced": the ten sharing questions (which carry the pictures) are shuffled into
  ten fixed slots and the ten accuracy questions stay put, two questions per page. So
  the accuracy question `k_accuracy` asks about whichever card was shown on page k,
  and the display-order string (`<block>_DO`) says which that was; --prep asserts that
  string has the fixed accuracy question in every second place. The authors' script
  makes the same reassignment. The accuracy question's own words ("the above
  headline") point to the card on its page.
* CONDITION. The instruction screen, then (Weak, Medium, Strong) the reminder screen,
  then the card. Word-for-word from the .qsf (HTML stripped, line breaks to spaces):
  - shared_context is the instruction text every arm shares: "Some headlines may be
    human-generated while others may be generated by artificial intelligence (AI). If
    you see AI-generated headlines, they will be explicitly labeled as such." The
    screen's first sentence, "Next, you will be presented with 10 news headlines and
    asked to answer a few questions about them.", is survey mechanics describing the
    whole sequence and is DROPPED (docs/CONVENTIONS.md, sequence signposting). The
    Control and No Definition screens are the same words (checked).
  - Weak, Medium and Strong add their definition ("AI-generated means that: - ...")
    and then the reminder screen ("As a reminder, AI-generated headlines means that:
    - ...", the source's grammar kept). Between the two, those arms answered two
    questions about the definition (a comprehension check); they are not narrated.
  - Then words that are OURS, "One of the headlines:", the card's words in quotation
    marks, and the <image> marker. Nothing is said of the other nine cards or where
    this one sat; the display order is recorded but random.
* ONE CONDITION, TWO ARMS. A Control person and a No Definition person who saw the
  same unlabelled card read the same instruction words and the same picture, so their
  rows are one condition (`raws` lists both codes). They differ only in what ELSE the
  person saw (labels on other cards), which a row cannot say; that spillover is the
  authors' RQ4 and is not built. In all, 90 conditions: 30 with no definition (20
  unlabelled cards, 10 labelled) and 20 for each definition (10 labelled AI-written
  cards, 9 human-written cards, and the unlabelled AI-written vaccine-injury card).
* PICTURES. 30 distinct cards, the OSF files unaltered: 10 stories x (human-written,
  AI-written, AI-written with the label). Human-written cards appear byte-identically
  in a Control and a Labels folder; the Control copy is catalogued. One Qualtrics
  graphic (the labelled veteran card) is a smaller copy, 900x898 against 1140x1138;
  same picture.
* WORDS IN THE PICTURES (text_in_image). The label line, the headline and the lede,
  word-for-word, " / " between blocks, line wraps joined with a space (a hyphen at a
  wrap is kept: "Asian-Pacific"). En and em dashes become "-". The source's spelling is
  kept: "teenagers ticket", "wasnt", "Ukraininan", "In just Few Weeks!". Left out and
  described instead: words inside photographs and logos (the CDC backdrop, the Russian
  slide, the airline's livery and boarding pass, the NATO summit logos, brand names on
  cans, the Us Weekly logo) and the letters AI inside the label's chip icon. The Adele
  collage's two caption boxes are printed text over the photographs and are kept.
* OUTCOMES. Two per card, in the order asked on the page: "If you saw this post
  online, how likely would you be to share it?" (1 Extremely unlikely .. 6 Extremely
  likely) and "How accurate is the claim in the above headline?" (1 Certainly false ..
  6 Certainly true). Identical in all 40 copies of each (checked); no recode; forced
  answers, no missing values among those built.
* NOT BUILT. The comprehension check (two questions on the definition: a check, not
  an outcome); the attention check; trust in news asked after the cards, what
  "AI-generated" means and what should be labelled (asked once, after all ten cards,
  so no single card is their condition); Study 1; the US sample.
* WHO. The authors' exclusions, which the consent page supports: Progress 99 or 100
  (the page says a person may withdraw "before submitting your answers ... by closing
  the browser"; a response that stopped short was withdrawn) and the attention check
  passed (`Attention_check_recoded` not 0). Then the UK sample: the Prolific ID is in
  one of the three UK exports. 1,500 people, none duplicated; --prep asserts the count.
  `pid` is the 1-based data row of Data.xlsx; the Prolific ID is not carried.
* PERSONA. Prolific's own records, stable facts collected before the study: age, sex,
  ethnicity (`Ethnicity simplified`, crosswalk scheme uk_ons_five_group_short),
  employment (scheme uk_prolific_rhfd6, the same Prolific export labels), student
  status, country of birth, nationality, and Prolific's UK political-affiliation
  screener (Left, Centre, Right; the sample's quota variable). Then the three trust
  statements of the screen asked BEFORE the cards (Q6, "To what extent do you agree or
  disagree with the following statements?"), answers word-for-word (Strongly
  disagree .. Strongly agree, seven points with "Tend to"): trust in news, in
  journalists and in news on social media. They are pre-treatment attitudes, the
  authors' baseline for H3; they correlate with the outcomes but no answer follows
  from them. Left absent: DATA_EXPIRED (ethnicity 1, employment 127, student status
  51, nationality 1, country of birth 1). Prolific's "Not in paid work (e.g.
  homemaker', 'retired or disabled)" has two stray quote marks from the export; they
  are typography and removed. Not mapped: country of residence (UK for everyone),
  `Language` (the export does not say whether it is first or fluent language), the
  Prolific submission status.
* UK FIT. The sample is British and was fielded these cards deliberately, to test the
  US finding outside the US. The ten stories: a WHO alcohol claim, a US-funded
  biolabs claim about Ukraine, a war veteran's medals, Adele's weight loss, a CDC
  vaccine-injury claim, Ontario's drinks-container deposit scheme, a Bangladeshi
  labour leader's death, British recruiters, American Airlines and "skiplagging", and
  NATO's Asia-Pacific partners. Three are about North American institutions (the CDC,
  a US airline's domestic route, Ontario and "The Beer Store"). The catalogue note
  calls one card US-specific without naming it; three qualify, so all three are
  flagged here. All are kept as fielded: the
  outcomes ask whether the claim seems accurate and whether one would share the post,
  which a UK reader can judge without local knowledge, and dropping a card would cut
  every person's set below the ten they saw. Flagged, not hidden: the US/Canadian
  cards measure how UK readers judge foreign news. American spelling on the cards is
  the source's ("labor", "honor", "canceled").
* NOT ASKED OF JEV. Assignment, card identity, persona and non-answer codes are
  settled by the .qsf flow, pixel comparison, Prolific's export labels and existing
  crosswalk precedents; no paid call.

    uv run python scripts/gen_a4y7s_study2.py --prep       # (re)write the coded long .xlsx
    uv run python scripts/gen_a4y7s_study2.py --catalogue  # check graphics, write images.json entries
    uv run python scripts/gen_a4y7s_study2.py              # write the recipe
    uv run python scripts/gen_a4y7s_study2.py --check      # exit 1 if it differs
"""

