def design() -> dict[tuple[str, str, str], list[int]]:
    """(definition, story, version) -> the card codes (arm*100 + picture) that showed it,
    in the order condition_num counts them."""
    block_sets = {"control": ["Control_A", "Control_B"]}
    cells: dict[tuple[str, str, str], list[int]] = {}
    for a, (key, _, _, _, level) in enumerate(INSTRUCTIONS, start=1):
        for block in block_sets.get(key, ["Label_A", "Label_B"]):
            for s in slots(block):
                story, version = s["picture"]
                code = a * 100 + picture_index(story, version)
                cells.setdefault((level, story, version), [])
                if code not in cells[(level, story, version)]:
                    cells[(level, story, version)].append(code)
    order = {(d, s, v): (DEFINITIONS.index(d), PICTURES.index((s, v))) for d, s, v in cells}
    return {k: sorted(cells[k]) for k in sorted(cells, key=order.__getitem__)}


