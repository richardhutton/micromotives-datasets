"""`docs/EXPERIMENTS.md` must describe the experiments that actually exist.

The doc is generated by `scripts/experiments_table.py` from four inputs — the recipes,
the built parquet, `uk_dataverse_provenance.json`, `tess_uk_foundation_sources.csv` and
`experiment_manifest.json`. Generating it removes most of the ways it could go stale, but
not all of them, and the two that remain are what this file covers:

1. **An experiment lands with no classification.** The generator prints `UNCLASSIFIED`
   rather than crashing, which is right for a doc and useless as a guard — a doc nobody
   re-reads would carry the word indefinitely. So an unclassified experiment fails here.
2. **A category gets invented at the call site.** The vocabulary is eight strings,
   declared once in the manifest, and the whole point of reusing TESS's six verbatim is
   that coverage can be counted across both layers. A typo or a ninth category invented
   in passing would split a count silently.

Deliberately NOT tested here: whether the file on disk is current. That is
`experiments_table.py --check`, which belongs in the commit path rather than the test
suite, because regenerating needs the built parquet and the suite has to pass on a fresh
clone where `data/processed/` is empty.
"""

from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[1]
GENERATOR = REPO / "scripts" / "experiments_table.py"
MANIFEST = REPO / "data" / "catalog" / "experiment_manifest.json"
RECIPES = REPO / "recipes"


def _module():
    spec = importlib.util.spec_from_file_location("experiments_table", GENERATOR)
    assert spec and spec.loader
    module = importlib.util.module_from_spec(spec)
    sys.modules["experiments_table"] = module
    spec.loader.exec_module(module)
    return module


def _manifest() -> dict:
    data: dict = json.loads(MANIFEST.read_text())
    return data


def _vocabulary() -> set[str]:
    return {k for k in _manifest()["_category_vocabulary"] if not k.startswith("_")}


@pytest.fixture(scope="module")
def experiments() -> list:
    return _module().collect()


def test_every_recipe_becomes_exactly_one_experiment(experiments: list) -> None:
    """No recipe silently dropped, none counted twice."""
    recipes = sorted(p.stem for p in RECIPES.glob("*.yaml"))
    assert sorted(e.recipe for e in experiments) == recipes


def test_every_experiment_is_classified(experiments: list) -> None:
    """The guard the generator cannot be: an experiment with no category fails.

    A new UK recipe needs an entry in `experiment_manifest.json`; a new TESS
    recipe needs its study_id to resolve in `tess_uk_foundation_sources.csv`.
    Either way someone has to say what the experiment is ABOUT, which is a
    judgement and therefore cannot be derived.
    """
    unclassified = sorted(e.recipe for e in experiments if e.category == "UNCLASSIFIED")
    assert not unclassified, (
        f"{len(unclassified)} experiment(s) have no category: {unclassified}. Add UK "
        f"experiments to data/catalog/experiment_manifest.json; a TESS experiment's "
        f"category comes from its study_id row in tess_uk_foundation_sources.csv."
    )


def test_every_category_comes_from_the_declared_vocabulary(experiments: list) -> None:
    """Eight strings, declared once, so counts cannot be split by a typo."""
    vocabulary = _vocabulary()
    unknown = sorted({e.category for e in experiments} - vocabulary)
    assert not unknown, (
        f"categor(ies) not in the declared vocabulary: {unknown}. "
        f"Declared: {sorted(vocabulary)}. Either fix the spelling or add the category to "
        f"_category_vocabulary in {MANIFEST.name} WITH a definition — an undefined "
        f"category cannot be argued with."
    )


def test_the_vocabulary_still_contains_tess_own_six() -> None:
    """The six reused categories are a compatibility promise, not a style choice.

    They are spelled exactly as `tess_uk_foundation_sources.csv` spells them so
    that a category count spans both layers. Renaming one here would silently
    orphan 28 experiments into `UNCLASSIFIED` — the join is on the string.
    """
    import pandas as pd

    tess = pd.read_csv(REPO / "data" / "catalog" / "tess_uk_foundation_sources.csv")
    theirs = set(tess["category"].dropna().unique())
    missing = sorted(theirs - _vocabulary())
    assert not missing, (
        f"TESS categor(ies) {missing} are no longer in the manifest vocabulary; the join "
        f"is on the literal string, so every experiment in them would fall out"
    )


def test_every_uk_experiment_carries_a_description_a_type_and_a_verification(
    experiments: list,
) -> None:
    """The four fields rich asked for, plus the one that makes the row trustworthy.

    `verified_against` is held to the same standard as the other three because a
    UK experiment with no answer key is not finished work — every one of the
    seven reproduces a number its own authors printed, and the doc says so per
    experiment rather than as a blanket claim in the preamble.
    """
    for experiment in [e for e in experiments if e.is_uk]:
        for field in ("description", "design", "verified_against"):
            value = getattr(experiment, field)
            assert value and value.strip(), f"{experiment.recipe} has no {field}"
        assert experiment.reference and experiment.reference.startswith("doi:"), (
            f"{experiment.recipe} has no DOI; it should come from uk_dataverse_provenance.json"
        )


def test_only_cc0_experiments_are_called_redistributable(experiments: list) -> None:
    """The licence line, derived from the recipe rather than from the layer.

    `publishable` keys on the recipe's own licence string, so a future Dataverse
    deposit under other terms, or a TESS deposit that ever acquires a licence,
    lands on the correct side without anyone remembering to move it. The test
    pins the thing that would actually hurt: something non-CC0 described as
    redistributable in a document people will act on.
    """
    for experiment in experiments:
        if experiment.publishable:
            assert (experiment.licence or "").startswith("CC0"), experiment.recipe
        if experiment.source == "tess":
            assert not experiment.publishable, (
                f"{experiment.recipe} is a TESS experiment marked redistributable. All 202 "
                f"TESS deposits were checked individually and none states a licence; if one "
                f"genuinely has, that needs recording in the catalogue and in embed.py's "
                f"CLEARED gate, not inferring from a recipe field"
            )
